#include "hm/generator/generator.hpp"

#include "hm/generator/util.hpp"
#include "hm/toolchain/compiler.hpp"
#include "hm/util/strings.hpp"
#include "hp/colors/color.hpp"
#include "hp/other/other.hpp"

#include <filesystem>
#include <sstream>
#include <string>
#include <string_view>

namespace hm::gen {

    class Clangd : public Generator {
      public:
        std::string_view name() const override {
            return ".clangd";
        }
        std::string_view Filename() const override {
            return ".clangd";
        }
        std::string_view description() const override {
            return ".clangd: Configuration File for Clangd";
        }

        bool generate(Config &cfg, const std::filesystem::path &projectRoot) override {
            auto comp = hm::makeCompiler(cfg.compiler);
            if (!comp) {
                hp::printlnCl("[Clangd] Unknown compiler '" + cfg.compiler + "'", hp::RED);
                return false;
            }

            std::ostringstream n;
            n << "# Generated by HelpMake. Do not edit.\n";
            n << "# Regenerate with: hm --gen .clangd" << (cfg.name.empty() ? "" : " --config " + cfg.name) << "\n\n";

            n << "CompileFlags:\n";
            n << "  Add:\n";
            n << "    - " << normalizeVersion(cfg.version, cfg.compiler) << '\n';

            for (const auto &flag : cfg.v_Flags) {
                n << "    - " << flag << '\n';
            }

            std::filesystem::path OutPath = projectRoot / std::string(Filename());
            return writeIfChanged(OutPath, n.str());
        }
    };

    std::unique_ptr<Generator> makeClangd() {
        return std::make_unique<Clangd>();
    }

} // namespace hm::gen